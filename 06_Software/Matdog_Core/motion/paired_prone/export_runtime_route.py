#!/usr/bin/env python3
"""Compile the frozen semantic route and exact hull plane extrema; never search poses."""
import hashlib, json, sys
import numpy as np
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent))
from paired_prone_model import PairModel, ROOT
BASE=ROOT/'09_Logs/Validation_Reports/Motion_Night_Run_2026-10-12'
DEST=ROOT/'05_Firmware/MATDOG_Controller/src/motion/PairedProneData.h'

def render():
    path=BASE/'continuous_pair_path.json'; raw=path.read_bytes(); d=json.loads(raw)
    assert len(d['segments'])==251 and d['original_contact_solved_samples']==242
    scene=PairModel().scene
    fields=('ur','lr','uf','lf','p','x','z','h')
    phases={'PRE_ALIGN':0,'REAR_DEPLOY':1,'FRONT_DEPLOY':2,'LOAD_TRANSFER':3,'CONTACT_LOCKED_RISE':4,'STAND_150':4,'STAND_100':4,'C4_C_RISE':4,'C4_RISE':4,'FLAT_CONTACT_RISE':4}
    lines=['// Generated by export_runtime_route.py from frozen MATDOG evidence. No approval implied.',
      '#ifndef MATDOG_PAIRED_PRONE_DATA_H','#define MATDOG_PAIRED_PRONE_DATA_H',
      'namespace matdog { namespace motion { namespace paired_data {',
      'struct Knot { double p[8]; };','struct Segment { double duration; unsigned char phase; };',
      f'constexpr char kRouteSha256[]="{hashlib.sha256(raw).hexdigest()}";',
      f'constexpr double kFootRadialBound={max(float(np.linalg.norm(scene.mesh(leg+"_foot_link").triangles_local.reshape(-1,3)[:,[0,2]]-[0,.0149],axis=1).max())-.0149 for leg in ("lf","rf","rh","lh")):.17g};',
      'constexpr Knot kKnots[] = {']
    knots=[d['segments'][0]['start_parameters']]+[s['end_parameters'] for s in d['segments']]
    for i,s in enumerate(d['segments']):
        assert s['start_parameters']==knots[i]
    for k in knots: lines.append('  {{'+','.join(format(k[f],'.17g') for f in fields)+'}},')
    lines+=['};','constexpr Segment kSegments[] = {']
    for s in d['segments']: lines.append('  {'+format(s['duration_s'],'.17g')+','+str(phases[s['phase']])+'},')
    lines+=['};','struct Hull { const Vector3* vertices; unsigned count; };']
    for i,n in enumerate(scene.model.collision_link_names):
        lines.append(f'constexpr Vector3 kHull{i}[] = {{')
        for v in scene.mesh(n).hull_vertices_local:
            lines.append('  {'+','.join(format(float(x),'.17g') for x in v)+'},')
        lines.append('};')
    lines.append('constexpr Hull kHulls[] = {')
    for i,n in enumerate(scene.model.collision_link_names):
        lines.append(f'  {{kHull{i},sizeof(kHull{i})/sizeof(Vector3)}}, // {n}')
    lines+=['};','} } }','#endif','']
    return '\n'.join(lines)
if __name__=='__main__':
    result=render()
    if '--check' in sys.argv:
        assert DEST.read_text()==result,'frozen route / canonical STL data drift'
        print('RUNTIME_ROUTE_REPRODUCIBLE=PASS')
    else:
        DEST.write_text(result);print(DEST)
