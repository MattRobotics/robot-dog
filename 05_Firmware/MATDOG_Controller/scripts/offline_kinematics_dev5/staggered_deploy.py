rear=Vq[:,6:12];print('rear joint range RH/LH upper',Vq[:,7].min().round(3),Vq[:,10].min().round(3),'lower max',Vq[:,8].max().round(3),Vq[:,11].max().round(3),'lo over kDeploy upper lo %.3f'%box[0,7]);
