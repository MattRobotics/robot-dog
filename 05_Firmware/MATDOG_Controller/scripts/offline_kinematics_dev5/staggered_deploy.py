 """rear right leg at route coordinate sr, rear left at sl, front and body at the leading leg."""
 m=max(sr,sl);qm=rt(m);p=pose(qm);ft=world(m).copy();ft[2]=world(sr)[2];ft[3]=world(sl)[3];q=qm.copy()
