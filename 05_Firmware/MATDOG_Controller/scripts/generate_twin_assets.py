#!/usr/bin/env python3
"""Generates src/network/TwinAssets.h from the viewer's dist-mobile/ package.

Input: the pre-gzipped files written by `npm run build:twin` in
06_Software/Matdog_Core/viewer/matdog_bno085_fullbody_viewer. Output: one
header with const byte arrays in flash (Content-Encoding: gzip), the content
type and a SHA-256 ETag per asset. Deterministic (gzip mtime 0, sorted).
Display assets only: no secret, no calibration, no command path.
"""
import argparse, hashlib, sys
from pathlib import Path

ASSETS = [  # (served path, file in dist-mobile, content type)
    ("/twin/", "mobile.html", "text/html; charset=utf-8"),
    ("/twin/assets/twin.js", "assets/twin.js", "text/javascript"),
    ("/twin/matdog_collision.mtw", "matdog_collision.mtw", "application/octet-stream"),
    ("/twin/matt_robodog_rev00.urdf", "matt_robodog_rev00.urdf", "application/xml"),
]

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dist", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    lines = ["// GENERATED by scripts/generate_twin_assets.py; DO NOT EDIT.",
             "// Phone Digital Twin served by the robot AP (WebGL runs on the phone).",
             "#ifndef MATDOG_NETWORK_TWIN_ASSETS_H", "#define MATDOG_NETWORK_TWIN_ASSETS_H",
             "#include <stddef.h>", "#include <stdint.h>",
             "namespace matdog { namespace network { namespace twin_assets {",
             "struct Asset { const char* path; const char* type; const char* etag; const uint8_t* gz; size_t gz_len; size_t raw_len; };"]
    total = 0
    for i, (path, name, ctype) in enumerate(ASSETS):
        raw = (a.dist / name).read_bytes()
        gz = (a.dist / (name + ".gz")).read_bytes()
        etag = '"' + hashlib.sha256(raw).hexdigest()[:32] + '"'
        total += len(gz)
        body = ",".join(str(b) for b in gz)
        lines.append(f"alignas(4) const uint8_t kAsset{i}[{len(gz)}] = {{{body}}};")
        lines.append(f"// {path}: raw {len(raw)} B, gzip {len(gz)} B, sha256 {hashlib.sha256(raw).hexdigest()}")
    lines.append("const Asset kAssets[] = {")
    for i, (path, name, ctype) in enumerate(ASSETS):
        raw = (a.dist / name).read_bytes()
        etag = '\\"' + hashlib.sha256(raw).hexdigest()[:32] + '\\"'
        lines.append(f'  {{"{path}", "{ctype}", "{etag}", kAsset{i}, sizeof(kAsset{i}), {len(raw)}}},')
    lines += ["};", f"constexpr size_t kAssetCount = {len(ASSETS)};", f"constexpr size_t kTotalGzipBytes = {total};",
              "} } }", "#endif", ""]
    a.out.write_text("\n".join(lines))
    print(f"TWIN_ASSETS={len(ASSETS)} total_gzip={total} out={a.out}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
